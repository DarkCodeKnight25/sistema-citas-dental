-- Esquema base del sistema de citas. Las horas se guardan en hora local de Lima (America/Lima).

create table doctor (
    id            bigint generated by default as identity primary key,
    nombre        varchar(120) not null,
    especialidad  varchar(80)  not null,
    tinta         varchar(7)   not null,
    activo        boolean      not null default true
);

create table tratamiento (
    id            bigint generated by default as identity primary key,
    nombre        varchar(120) not null,
    descripcion   varchar(240),
    duracion_min  integer      not null check (duracion_min between 15 and 240),
    precio_ref    numeric(8,2) not null check (precio_ref >= 0),
    activo        boolean      not null default true
);

create table doctor_tratamiento (
    doctor_id      bigint not null references doctor(id),
    tratamiento_id bigint not null references tratamiento(id),
    primary key (doctor_id, tratamiento_id)
);

-- Bloques de atención; un día puede tener dos bloques (mañana y tarde) por el corte de almuerzo.
create table horario (
    id           bigint generated by default as identity primary key,
    doctor_id    bigint   not null references doctor(id),
    dia_semana   smallint not null check (dia_semana between 1 and 7),
    hora_inicio  time     not null,
    hora_fin     time     not null,
    check (hora_fin > hora_inicio)
);

create table feriado (
    fecha   date primary key,
    nombre  varchar(120) not null
);

create table paciente (
    id          bigint generated by default as identity primary key,
    nombres     varchar(80)  not null,
    apellidos   varchar(80)  not null,
    dni         varchar(8)   unique,
    celular     varchar(9)   not null,
    fecha_nac   date,
    alergias    varchar(240),
    creado_en   timestamp    not null
);
create index ix_paciente_celular on paciente(celular);

create table cita (
    id              bigint generated by default as identity primary key,
    codigo          varchar(12)  not null unique,
    paciente_id     bigint       not null references paciente(id),
    doctor_id       bigint       not null references doctor(id),
    tratamiento_id  bigint       not null references tratamiento(id),
    inicio          timestamp    not null,
    fin             timestamp    not null,
    estado          varchar(16)  not null,
    origen          varchar(12)  not null,
    nota            varchar(400),
    creado_en       timestamp    not null,
    actualizado_en  timestamp    not null,
    check (fin > inicio)
);
create index ix_cita_doctor_inicio on cita(doctor_id, inicio);
create index ix_cita_inicio on cita(inicio);

create table recordatorio (
    id               bigint generated by default as identity primary key,
    cita_id          bigint      not null references cita(id) on delete cascade,
    tipo             varchar(16) not null,
    programado_para  timestamp   not null,
    estado           varchar(12) not null,
    enviado_en       timestamp,
    enviado_por      varchar(80)
);
create index ix_recordatorio_estado on recordatorio(estado, programado_para);

create table nota_clinica (
    id           bigint generated by default as identity primary key,
    paciente_id  bigint        not null references paciente(id) on delete cascade,
    doctor_id    bigint        not null references doctor(id),
    cita_id      bigint        references cita(id) on delete set null,
    texto        varchar(2000) not null,
    creado_en    timestamp     not null
);

create table usuario (
    id             bigint generated by default as identity primary key,
    email          varchar(120) not null unique,
    nombre         varchar(120) not null,
    password_hash  varchar(100) not null,
    rol            varchar(12)  not null,
    doctor_id      bigint references doctor(id)
);
